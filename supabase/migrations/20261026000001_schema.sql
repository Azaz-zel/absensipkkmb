-- Skema absensi PKKMB. Semua akses data lewat API Go dengan role app_api;
-- anon/authenticated (PostgREST) sengaja tidak diberi akses apa pun.

create type peran as enum ('admin', 'pj', 'manajer');
create type status_akun as enum ('aktif', 'nonaktif');
create type kategori_kelas as enum ('pagi', 'malam');
create type status_sesi_kelas as enum ('belum_dibuka', 'dibuka', 'ditutup');
create type status_hadir as enum ('hadir', 'izin', 'sakit', 'alpa');

create table users (
  id bigint generated by default as identity primary key,
  name text not null check (length(name) between 1 and 255),
  email text not null unique check (length(email) <= 255),
  username text unique check (length(username) <= 255),
  password text not null,
  role peran not null default 'pj',
  status status_akun not null default 'aktif',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table kelas (
  id bigint generated by default as identity primary key,
  nama_kelas text not null unique check (nama_kelas ~ '^[A-Z]{1,2}$'),
  kategori kategori_kelas not null,
  kapasitas integer check (kapasitas is null or kapasitas >= 1),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table kelas_user (
  user_id bigint not null references users(id) on delete cascade,
  kelas_id bigint not null references kelas(id) on delete cascade,
  primary key (user_id, kelas_id)
);
create index on kelas_user (kelas_id);

create table mahasiswa (
  id bigint generated by default as identity primary key,
  nama text not null check (length(nama) between 1 and 255),
  nim text not null check (length(nim) between 1 and 50),
  jurusan text not null check (length(jurusan) between 1 and 255),
  kelas_id bigint not null references kelas(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);
-- NIM boleh dipakai ulang setelah datanya dihapus (soft delete).
create unique index mahasiswa_nim_aktif on mahasiswa (nim) where deleted_at is null;
create index on mahasiswa (kelas_id) where deleted_at is null;

create table sesi_absensi (
  id bigint generated by default as identity primary key,
  nama_sesi text not null check (length(nama_sesi) between 1 and 255),
  tanggal date not null,
  created_by bigint references users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table sesi_kelas (
  id bigint generated by default as identity primary key,
  sesi_absensi_id bigint not null references sesi_absensi(id) on delete cascade,
  kelas_id bigint not null references kelas(id) on delete cascade,
  status status_sesi_kelas not null default 'belum_dibuka',
  opened_at timestamptz,
  closed_at timestamptz,
  opened_by bigint references users(id) on delete set null,
  closed_by bigint references users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (sesi_absensi_id, kelas_id)
);

create table absensi (
  id bigint generated by default as identity primary key,
  mahasiswa_id bigint not null references mahasiswa(id) on delete cascade,
  kelas_id bigint not null references kelas(id) on delete cascade,
  sesi_absensi_id bigint not null references sesi_absensi(id) on delete cascade,
  status status_hadir not null,
  recorded_by bigint references users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (mahasiswa_id, sesi_absensi_id)
);
create index on absensi (sesi_absensi_id, kelas_id);

create table pelanggaran (
  id bigint generated by default as identity primary key,
  mahasiswa_id bigint not null references mahasiswa(id) on delete cascade,
  jenis text not null check (length(jenis) between 1 and 255),
  poin integer not null check (poin between 1 and 20),
  dicatat_oleh bigint references users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index on pelanggaran (mahasiswa_id);
create index on pelanggaran (created_at);

create table riwayat_perubahan (
  id bigint generated by default as identity primary key,
  user_id bigint references users(id) on delete set null,
  nama_pelaku text not null,
  aksi text not null check (length(aksi) <= 60),
  keterangan text not null,
  created_at timestamptz not null default now()
);
create index on riwayat_perubahan (aksi);
create index on riwayat_perubahan (created_at);

-- Sesi login milik API. Token disimpan sebagai hash SHA-256, bukan token mentah.
create table sesi_login (
  token_hash bytea primary key,
  user_id bigint not null references users(id) on delete cascade,
  last_active_at timestamptz not null default now(),
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);
create index on sesi_login (user_id);

-- Hasil pratinjau import Excel, menunggu dikonfirmasi admin (kedaluwarsa 30 menit).
create table import_tertunda (
  token uuid primary key,
  user_id bigint not null references users(id) on delete cascade,
  rows jsonb not null,
  expires_at timestamptz not null
);

-- Kunci akses: RLS di semua tabel, hanya app_api yang punya policy.
do $$
declare t text;
begin
  if not exists (select 1 from pg_roles where rolname = 'app_api') then
    create role app_api login noinherit;
  end if;
  foreach t in array array['users','kelas','kelas_user','mahasiswa','sesi_absensi','sesi_kelas',
                           'absensi','pelanggaran','riwayat_perubahan','sesi_login','import_tertunda'] loop
    execute format('alter table %I enable row level security', t);
    execute format('alter table %I force row level security', t);
    execute format('revoke all on %I from anon, authenticated', t);
    execute format('grant select, insert, update, delete on %I to app_api', t);
    execute format('create policy app_api_all on %I for all to app_api using (true) with check (true)', t);
  end loop;
end $$;

grant usage on schema public to app_api;
grant usage, select on all sequences in schema public to app_api;
revoke all on all sequences in schema public from anon, authenticated;
-- Riwayat hanya boleh ditambah, tidak diubah/dihapus lewat API.
revoke update, delete on riwayat_perubahan from app_api;
